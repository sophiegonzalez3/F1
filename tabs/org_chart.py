@callback(Output("org-icicle", "figure"),
          [Input("org-team", "value"),
           Input("org-reset", "n_clicks"),
           Input("org-icicle", "clickData")],
          State("org-icicle", "figure"),
          prevent_initial_call=True)
def _update_org_icicle(team, _reset_clicks, click, fig):
    """Redraw the chart, and stop a click on a person from stranding the viewer.

    Plotly zooms into whatever tile you click. For a branch that is what you want;
    for a person it dives into a single tile with nothing inside it, and this
    Plotly build (6.8) draws no pathbar to climb back out of it — so a stray click
    on a name is a dead end. Person ids are the only ones carrying '#', so when
    one is clicked we redraw at that person's parent instead: the viewer stays
    exactly where they were and the click is simply inert.
    """
    trigger = ctx.triggered_id
    if trigger == "org-icicle":
        points = (click or {}).get("points") or []
        clicked = points[0].get("id", "") if points else ""
        if "#" not in clicked:
            return no_update  # a branch: let Plotly's own zoom do its job
        parent = clicked.rsplit("|", 1)[0]
        return _icicle_fig(org_annotated(), team, level=parent)
    return _icicle_fig(org_annotated(), team)
