"""
Org-structure section — a seat-level map of who holds which job at each team,
sitting directly under the staff-moves board it shares a subject with.

Data comes in two layers.

  data/org_structure.csv is GENERATED by scripts/parse_org_structure.py from a
  community-maintained document (data/org_structure_raw.txt) compiled from public
  LinkedIn profiles and posted to the f1technical "Moving F1-Staff" thread on
  2026-08-05. Never hand-edit it; a re-parse overwrites it.

  data/org_overrides.csv is the curated layer on top, and is where our own
  verification lives — one row per confirm / correct / add / remove, each carrying
  the source URL and a source_type. That separation is the point: the document has
  real errors (a team principal's title on the wrong person, four misspelt race
  engineers) and we need those fixes to survive the next re-parse.

Every seat therefore carries a source_type: community-doc (unverified), press,
official (F1/FIA), or first-party (the team's own announcement). It drives the
"Verified" column, the pale tile border in the org chart, and one of the KPIs —
so the unverified bulk is never presented as though it were checked.

WHAT THIS IS NOT: a headcount census. The document names 7.8% (Alpine) to 20.5%
(Audi) of each team's real staff, and covers Production at ~7% of entries where a
real F1 team runs nearer 30% — engineers keep public LinkedIn profiles, machinists
and technicians largely do not. So the raw seat counts measure how visible and how
thoroughly covered a team is, NOT how big it is. Every count here is labelled
"seats mapped" for that reason, and the real-headcount bar in the Team Size card
above remains the only honest size comparison.

What it IS good for, and why it earns a place next to staff_moves.csv:
  - looking up who currently holds a named seat, with the department around them;
  - joining our tracked moves to a destination *seat*, so "X went to Williams"
    becomes "X went to Williams as Head of Model Design, in Aerodynamics";
  - the churn view — of the seats we can see in a department, what share are
    people who arrived recently. That is a ratio inside one biased sample, so
    the coverage bias largely divides out, unlike the raw counts.
"""
